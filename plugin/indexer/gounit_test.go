const goKitUnit = "go:example.com/kit@v1.0.0"

// goKitFiles is a Go module with a file of each kind that the index keeps
// or leaves out. tables.go is a generated table file whose var holds a
// string of 60 parts, which nests past the depth limit of the index. Its
// Lookup calls helper, and its second var calls helper too.
func goKitFiles() map[string]string {
	parts := strings.Repeat(` + "x"`, 60)
	return map[string]string{
		"go.mod":         "module example.com/kit\n\ngo 1.22\n",
		"kit.go":         "package kit\n\nfunc Run() { helper() }\n\nfunc helper() {}\n",
		"kit_test.go":    "package kit\n\nimport \"testing\"\n\nfunc TestRun(t *testing.T) { Run() }\n",
		"kit_windows.go": "//go:build windows\n\npackage kit\n\nfunc OnlyWindows() {}\n",
		"kit_linux.go":   "package kit\n\nfunc OnlyLinux() {}\n",
		"kit_purego.go":  "//go:build purego\n\npackage kit\n\nfunc PureGo() {}\n",
		"gen.go":         "//go:build ignore\n\npackage main\n\nfunc main() {}\n",
		"tables.go":      "// Code generated by synth. DO NOT EDIT.\n\npackage kit\n\nfunc Lookup() int { helper(); return len(data) }\n\nvar data string = \"\"" + parts + "\n\nvar ready = helper\n",
	}
}

func TestIndexerReadsTheGoBuildsOfADependencyUnit(t *testing.T) {
	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{"main.go": "package main\n\nfunc main() {}\n", "main_test.go": "package main\n"})
	kit := filepath.Join(dir, "vendor", "kit")
	writeFiles(t, kit, goKitFiles())
	fsys, err := fs.NewLocalFileSystem(fs.LocalFileSystemConfig{
		AppDirectories:    []string{dir},
		ImportDirectories: []string{kit},
		ImportUnits:       map[string]string{kit: goKitUnit},
		ExcludePatterns:   []*regexp.Regexp{fs.SkipPattern(kit)},
	})
	require.NoError(t, err)
	result, err := runIndexer(t, context.Background(), fsys, Options{Languages: languages(t, core.LanguageCodeGo), Store: memstore.New(), Imports: true})
	require.NoError(t, err)

	var indexed, excluded []string
	for p, status := range result.Dependencies {
		_, inner := fileindex.SplitUnit(p)
		assert.Equal(t, fileindex.FileIndexed, status, p)
		indexed = append(indexed, inner)
	}
	for _, p := range result.Excluded {
		_, inner := fileindex.SplitUnit(p)
		excluded = append(excluded, inner)
	}
	assert.ElementsMatch(t, []string{"kit.go", "kit_linux.go", "kit_windows.go", "tables.go"}, indexed, "a file that any platform builds stays")
	assert.ElementsMatch(t, []string{"gen.go", "kit_purego.go", "kit_test.go"}, excluded)
	assert.Equal(t, map[string]fileindex.FileStatus{"main.go": fileindex.FileIndexed, "main_test.go": fileindex.FileIndexed}, result.Files, "a test file of the project stays")

	var tables *fileindex.Index
	for _, ix := range result.Indexes {
		if ix.Path == goKitUnit+"//tables.go" {
			tables = ix
		}
	}
	require.NotNil(t, tables)
	assert.Empty(t, tables.Truncated, "the skeleton of the table file hits no limit")
	var keys, callees []string
	for _, def := range tables.Definitions {
		keys = append(keys, def.Key)
	}
	for _, call := range tables.Calls {
		callees = append(callees, call.Callee)
	}
	assert.Contains(t, keys, goKitUnit+"//tables.go//Lookup")
	assert.Contains(t, callees, "helper", "the skeleton keeps the bodies")
}

func TestGoSkeletonKeepsTheHashOfTheFile(t *testing.T) {
	dir := t.TempDir()
	kit := filepath.Join(dir, "kit")
	writeFiles(t, kit, goKitFiles())
	fsys, err := fs.NewLocalFileSystem(fs.LocalFileSystemConfig{AppDirectories: []string{dir}, ImportDirectories: []string{kit}, ImportUnits: map[string]string{kit: goKitUnit}, ExcludePatterns: []*regexp.Regexp{fs.SkipPattern(kit)}})
	require.NoError(t, err)
	s := memstore.New()
	opts := Options{Languages: languages(t, core.LanguageCodeGo), Store: s, Imports: true}
	_, err = runIndexer(t, context.Background(), fsys, opts)
	require.NoError(t, err)
	result, err := runIndexer(t, context.Background(), fsys, opts)
	require.NoError(t, err)
	assert.Equal(t, fileindex.FileCached, result.Dependencies[goKitUnit+"//tables.go"], "the store serves the skeleton index on the next run")
}
